[CmdletBinding()]
param(
    [switch]$Copy
)

$ErrorActionPreference = 'Stop'

$profilePath = $PROFILE.CurrentUserCurrentHost
$profileDir = Split-Path -Path $profilePath -Parent
$modulesDir = Join-Path -Path $PSScriptRoot -ChildPath 'modules'
$bundledPath = Join-Path -Path $PSScriptRoot -ChildPath 'Microsoft.PowerShell_profile.ps1'

if (-not (Test-Path -LiteralPath $modulesDir -PathType Container)) {
    throw "Modules directory not found: $modulesDir"
}

# 1. Bundle modules/*.ps1 into Microsoft.PowerShell_profile.ps1 for single-file distribution (setup.ps1)
$moduleFiles = @(Get-ChildItem -LiteralPath $modulesDir -Filter '*.ps1' -File | Sort-Object Name)
if ($moduleFiles.Count -eq 0) {
    throw "No module files (*.ps1) found in: $modulesDir"
}

$bundleBuilder = [System.Text.StringBuilder]::new()
[void]$bundleBuilder.AppendLine('### PowerShell Profile (Bundled from modules/*.ps1 via setprofile.ps1)')
[void]$bundleBuilder.AppendLine('# Do not edit this bundled file directly; edit files in modules/ and run ./setprofile.ps1')
[void]$bundleBuilder.AppendLine()

foreach ($file in $moduleFiles) {
    $content = Get-Content -LiteralPath $file.FullName -Raw -Encoding UTF8
    if (-not [string]::IsNullOrEmpty($content)) {
        [void]$bundleBuilder.AppendLine($content.TrimEnd())
        [void]$bundleBuilder.AppendLine()
    }
}

$bundleBuilder.ToString().TrimEnd() + "`n" | Set-Content -LiteralPath $bundledPath -Encoding UTF8 -NoNewline
Write-Host "Bundled $($moduleFiles.Count) modules into [$bundledPath]." -ForegroundColor Cyan

# 2. Configure local $PROFILE.CurrentUserCurrentHost
if (-not (Test-Path -LiteralPath $profileDir -PathType Container)) {
    New-Item -Path $profileDir -ItemType Directory -Force | Out-Null
}

if ($Copy) {
    Copy-Item -LiteralPath $bundledPath -Destination $profilePath -Force
    Write-Host "Copied bundled profile to [$profilePath]." -ForegroundColor Green
}
else {
    $escapedModulesDir = $modulesDir -replace "'", "''"
    $escapedBundledPath = $bundledPath -replace "'", "''"
    $loaderContent = @"
# Auto-generated by setprofile.ps1 — Links directly to local git repository modules
`$global:IsRepoLinkedProfile = `$true
`$script:IsRepoLinkedProfile = `$true
`$repoModulesDir = '$escapedModulesDir'
if (Test-Path -LiteralPath `$repoModulesDir -PathType Container) {
    foreach (`$moduleFile in (Get-ChildItem -LiteralPath `$repoModulesDir -Filter '*.ps1' -File | Sort-Object Name)) {
        . `$moduleFile.FullName
    }
}
else {
    . '$escapedBundledPath'
}
"@
    $loaderContent | Set-Content -LiteralPath $profilePath -Encoding UTF8
    Write-Host "Linked [$profilePath] -> [$modulesDir]." -ForegroundColor Green
}

# 3. Provision one-time XDG environment and rebuild cached init scripts
$global:IsRepoLinkedProfile = $true
$script:IsRepoLinkedProfile = $true
. $profilePath
Initialize-XdgEnvironment -Force
Clear-InitCache
